de Dados Pessoais – LGPD).
</p>

<p class="text-slate-700 leading-relaxed mb-10">
Esta Política de Privacidade descreve como os dados pessoais
são coletados, utilizados, armazenados e protegidos quando
o usuário acessa ou utiliza os serviços digitais do CEEP Assaí.
</p>

<hr class="my-10">

<h2 class="text-2xl font-bold text-slate-900 mb-4">
1. Dados coletados
</h2>

<p class="text-slate-600 leading-relaxed mb-4">
O portal do CEEP Assaí coleta apenas os dados estritamente
necessários para o funcionamento dos sistemas educacionais,
administrativos e institucionais.
</p>

<ul class="list-disc pl-6 space-y-2 text-slate-600 mb-8">
<li>Dados de identificação (nome, CPF, RG, data de nascimento)</li>
<li>Dados de contato (telefone, e-mail)</li>
<li>Dados acadêmicos e institucionais</li>
<li>Dados técnicos de navegação (endereço IP, tipo de navegador)</li>
</ul>

<hr class="my-10">

<h2 class="text-2xl font-bold text-slate-900 mb-4">
2. Finalidade do uso dos dados
</h2>

<p class="text-slate-600 leading-relaxed mb-6">
Os dados pessoais são utilizados exclusivamente para finalidades
legítimas, específicas e necessárias, tais como:
</p>

<ul class="list-disc pl-6 space-y-2 text-slate-600 mb-8">
<li>Gestão acadêmica e administrativa</li>
<li>Comunicação institucional</li>
<li>Cumprimento de obrigações legais</li>
<li>Melhoria dos serviços educacionais</li>
</ul>

<hr class="my-10">

<h2 class="text-2xl font-bold text-slate-900 mb-4">
3. Compartilhamento de dados
</h2>

<p class="text-slate-600 leading-relaxed mb-8">
O CEEP Assaí não comercializa dados pessoais.
O compartilhamento ocorre apenas quando exigido por lei
ou para cumprimento de obrigações legais e institucionais,
respeitando os princípios da LGPD.
</p>

<hr class="my-10">

<h2 class="text-2xl font-bold text-slate-900 mb-4">
4. Armazenamento e segurança
</h2>

<p class="text-slate-600 leading-relaxed mb-8">
São adotadas medidas técnicas e organizacionais adequadas
para proteger os dados pessoais contra acessos não autorizados,
perda, alteração ou divulgação indevida.
</p>

<hr class="my-10">

<h2 class="text-2xl font-bold text-slate-900 mb-4">
5. Direitos do titular
</h2>

<p class="text-slate-600 leading-relaxed mb-4">
Nos termos da LGPD, o titular dos dados pode solicitar:
</p>

<ul class="list-disc pl-6 space-y-2 text-slate-600 mb-8">
<li>Confirmação da existência de tratamento</li>
<li>Acesso aos dados</li>
<li>Correção de dados incompletos ou desatualizados</li>
<li>Eliminação de dados, quando aplicável</li>
</ul>

<hr class="my-10">

